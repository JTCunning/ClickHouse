#!/usr/bin/env python3
"""Set an outbox item's status (and optional fields) in index.json, then rebuild README.md.

Usage: python3 outbox/set_status.py <slug> <status|keep> [field=value ...]
Examples:
  python3 outbox/set_status.py grid-gap-wraparound submitted submitted_head=4629104 upstream_pr=128500
  python3 outbox/set_status.py rollup-samples keep decision="Rename the setting? Answer on #16."
  python3 outbox/set_status.py rollup-samples keep decision=
`keep` leaves the status as it is. An empty value (`decision=`) removes the field.
issue, upstream_pr and priority are stored as numbers. README.md is generated by render.py: never edit it by hand.
"""
import pathlib
import sys

sys.dont_write_bytecode = True  # keep __pycache__ out of the research repository
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import render  # noqa: E402

if len(sys.argv) < 3:
    sys.exit(__doc__)
slug, status, fields = sys.argv[1], sys.argv[2], sys.argv[3:]

index = render.load()
if status != "keep" and status not in index["statuses"]:
    sys.exit(f"unknown status {status!r}; known: keep, {', '.join(index['statuses'])}")
item = next((i for i in index["items"] if i["slug"] == slug), None)
if item is None:
    sys.exit(f"no item {slug!r}")

if status != "keep":
    item["status"] = status
for f in fields:
    key, sep, value = f.partition("=")
    if not sep:
        sys.exit(f"not field=value: {f!r}")
    if value == "":
        item.pop(key, None)
    else:
        item[key] = int(value) if key in ("issue", "upstream_pr", "priority") and value.isdigit() else value
render.save(index)
print(f"{slug}: {item['status']} (index.json and README.md updated)")
